// Execute with Playwright CLI against the production preview URL with ?qa=1.
async (page) => {
  const report = { checks: [], errors: [], warnings: [], failedRequests: [], environments: [] };
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  const check = (message) => report.checks.push(message);
  const snapshot = (target = page) => target.evaluate(() => window.beaconSnapshot());
  const url = page.url();
  assert(new URL(url).pathname === '/beacon-shift-phaser/', 'Use the production base path');
  const watch = (target) => {
    target.on('pageerror', error => report.errors.push(error.message));
    target.on('console', message => {
      if (message.type() === 'error') report.errors.push(message.text());
      if (message.type() === 'warning') report.warnings.push(message.text());
    });
    target.on('requestfailed', request => report.failedRequests.push(`${request.url()}: ${request.failure()?.errorText}`));
  };
  try {
  watch(page);
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(url);
  await page.getByRole('button', { name: 'Begin watch ↗' }).waitFor();
  await page.evaluate(() => document.fonts.ready);
  report.environments.push({ type: 'desktop', viewport: '1440x900', userAgent: await page.evaluate(() => navigator.userAgent) });
  const bounds = await page.locator('canvas').boundingBox();
  assert(bounds && Math.abs(bounds.width - bounds.height) < 1, 'Square rendered arena');
  await page.screenshot({ path: 'output/playwright/desktop.png' });
  await page.getByRole('button', { name: 'Begin watch ↗' }).click();
  let state = await snapshot();
  assert(state.phase === 'playing' && state.elapsed < .15 && state.score === 0 && state.enemies.length === 0, 'Start consumes its click');
  check('Start produces a clean run with no secondary input.');
  for (const angle of [0, Math.PI / 2, Math.PI - .02, -Math.PI + .02, -Math.PI / 2]) {
    await page.mouse.move(bounds.x + bounds.width * (.5 + Math.cos(angle) * .4), bounds.y + bounds.height * (.5 + Math.sin(angle) * .4));
    state = await snapshot();
    assert(Math.abs(Math.atan2(Math.sin(state.beamAngle - angle), Math.cos(state.beamAngle - angle))) < .01, 'Pointer maps scaled canvas including angular wrap');
  }
  check('Mouse aim maps edges and -pi/pi wrap correctly.');
  const beforeKey = (await snapshot()).beamAngle;
  await page.keyboard.down('ArrowRight');
  await page.waitForTimeout(240);
  state = await snapshot();
  assert(state.inputSource === 'keyboard' && state.beamAngle > beforeKey + .3, 'Keyboard rotation');
  await page.mouse.move(bounds.x + bounds.width * .9, bounds.y + bounds.height * .5);
  const pointerAngle = (await snapshot()).beamAngle;
  await page.waitForTimeout(200);
  assert(Math.abs((await snapshot()).beamAngle - pointerAngle) < .001, 'Pointer clears held keyboard input');
  await page.keyboard.up('ArrowRight');
  await page.keyboard.down('a');
  await page.waitForTimeout(180);
  assert((await snapshot()).beamAngle < pointerAngle - .2, 'A rotates left after mouse');
  await page.keyboard.up('a');
  check('Keyboard arrows/A and last-modality pointer control work without sticking.');
  await page.locator('#restart').focus();
  const unfocusedAngle = (await snapshot()).beamAngle;
  await page.keyboard.down('ArrowRight');
  await page.waitForTimeout(140);
  await page.keyboard.up('ArrowRight');
  assert((await snapshot()).beamAngle === unfocusedAngle, 'Navigation keys outside arena are not captured');
  await page.locator('#arena-frame').focus();
  check('Arrow keys outside the arena preserve page navigation.');
  await page.getByRole('button', { name: 'Pause', exact: true }).click();
  const paused = await snapshot();
  await page.screenshot({ path: 'output/playwright/paused.png' });
  await page.waitForTimeout(900);
  assert(JSON.stringify(await snapshot()) === JSON.stringify(paused), 'Pause freezes all simulation and input');
  assert(await page.locator('#continue').evaluate(el => el === document.activeElement), 'Pause focuses its resume action');
  await page.getByRole('button', { name: 'Resume watch ↗' }).click();
  await page.waitForTimeout(200);
  assert((await snapshot()).elapsed > paused.elapsed && (await snapshot()).elapsed < paused.elapsed + .35, 'Resume has no time jump');
  check('Pause freezes state and focuses intentional Resume; resume has no time jump.');
  await page.keyboard.down('d');
  await page.waitForTimeout(100);
  await page.evaluate(() => window.dispatchEvent(new Event('blur')));
  state = await snapshot();
  assert(state.phase === 'paused' && state.pressed.length === 0, 'Blur handler pauses and clears keys');
  await page.keyboard.up('d');
  check('Synthetic blur handler clears held keys and pauses.');
  await page.getByRole('button', { name: 'Resume watch ↗' }).click();
  const other = await page.context().newPage();
  await other.goto('about:blank');
  await other.bringToFront();
  await page.waitForTimeout(400);
  const visibility = await page.evaluate(() => document.visibilityState);
  const background = await snapshot();
  await page.waitForTimeout(700);
  const backgroundLater = await snapshot();
  report.background = { visibility, phase: background.phase, frozen: background.elapsed === backgroundLater.elapsed };
  await other.close();
  await page.bringToFront();
  if (visibility === 'hidden') {
    assert(background.phase === 'paused' && background.elapsed === backgroundLater.elapsed, 'True background tab freezes run');
    assert((await snapshot()).phase === 'paused', 'Returning requires intentional resume');
    check('Actual headed background tab is hidden, freezes the run and requires resume.');
  } else check('Automation did not expose a truly hidden tab; synthetic handler test is distinguished.');
  if ((await snapshot()).phase === 'paused') await page.getByRole('button', { name: 'Resume watch ↗' }).click();
  for (let index = 0; index < 10; index++) {
    await page.getByRole('button', { name: 'Restart ↻', exact: true }).click();
    state = await snapshot();
    assert(state.elapsed < .12 && state.lives === 3 && state.score === 0 && state.enemies.length === 0 && state.nextId === 1 && state.immunity === 0, 'Full restart');
    assert(await page.locator('canvas').count() === 1, 'One canvas after each restart');
  }
  await page.waitForTimeout(1600);
  assert((await snapshot()).enemies.length === 1, 'Restart leaves one spawn timer');
  check('Ten restarts clear every run field and keep one canvas and one spawn schedule.');
  for (let index = 0; index < 12; index++) await page.keyboard.press('p');
  assert((await snapshot()).phase === 'playing', 'Rapid pause toggles remain predictable');
  check('Twelve rapid pause/resume toggles return to playing.');
  await page.getByRole('button', { name: 'Restart ↻', exact: true }).click();
  await page.mouse.move(bounds.x + bounds.width * .5, bounds.y + bounds.height * .06);
  await page.waitForFunction(() => window.beaconSnapshot().phase === 'lost', { timeout: 35000 });
  report.loss = await snapshot();
  assert(report.loss.lives === 0 && report.loss.elapsed < 60, 'Natural loss without state edits');
  await page.screenshot({ path: 'output/playwright/lost.png' });
  check('An unattended real-time run loses all three lives and shows a usable result screen.');
  await page.getByRole('button', { name: 'Another watch ↻' }).click();
  assert((await snapshot()).lives === 3, 'Result restart');
  await page.getByRole('button', { name: 'Pause', exact: true }).click();
  await page.setViewportSize({ width: 360, height: 800 });
  await page.screenshot({ path: 'output/playwright/mobile-paused.png' });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'No portrait horizontal overflow');
  const mobileContext = await page.context().browser().newContext({ viewport: { width: 360, height: 800 }, hasTouch: true, isMobile: true, deviceScaleFactor: 2, reducedMotion: 'reduce' });
  const mobile = await mobileContext.newPage();
  watch(mobile);
  await mobile.goto(url);
  await mobile.getByRole('button', { name: 'Begin watch ↗' }).waitFor();
  await mobile.evaluate(() => document.fonts.ready);
  await mobile.screenshot({ path: 'output/playwright/mobile.png' });
  await mobile.getByRole('button', { name: 'Begin watch ↗' }).tap();
  await mobile.waitForFunction(() => window.beaconSnapshot().phase === 'playing');
  const touchBounds = await mobile.locator('canvas').boundingBox();
  const touch = await mobileContext.newCDPSession(mobile);
  const cx = touchBounds.x + touchBounds.width * .9;
  const cy = touchBounds.y + touchBounds.height * .5;
  await touch.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: cx, y: cy }] });
  assert(Math.abs((await snapshot(mobile)).beamAngle) < .02, 'Touch down maps correctly');
  await touch.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: touchBounds.x + touchBounds.width * .5, y: touchBounds.y + touchBounds.height * .9 }] });
  assert(Math.abs((await snapshot(mobile)).beamAngle - Math.PI / 2) < .02, 'Touch drag maps correctly');
  await touch.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  await mobile.screenshot({ path: 'output/playwright/mobile-playing.png' });
  assert(await mobile.locator('canvas').evaluate(el => getComputedStyle(el).touchAction === 'none'), 'Canvas contains touch gesture');
  assert(await mobile.locator('body').evaluate(el => getComputedStyle(el).touchAction === 'auto'), 'Page navigation remains available');
  report.environments.push({ type: 'emulated touch, reduced motion', viewport: '360x800', userAgent: await mobile.evaluate(() => navigator.userAgent) });
  check('Emulated touch down and drag map correctly at 360x800; page touch remains unrestricted.');
  await mobile.setViewportSize({ width: 800, height: 360 });
  await mobile.waitForTimeout(350);
  await mobile.screenshot({ path: 'output/playwright/landscape.png' });
  assert(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'No landscape horizontal overflow');
  report.landscapeBeforePause = await mobile.evaluate(() => ({ phase: window.beaconSnapshot().phase, viewport: { width: innerWidth, height: innerHeight, scale: visualViewport.scale }, bounds: document.getElementById('pause').getBoundingClientRect().toJSON() }));
  await mobile.getByRole('button', { name: 'Pause', exact: true }).tap();
  await mobile.waitForTimeout(300);
  report.landscapeAfterPause = await snapshot(mobile);
  await mobile.waitForFunction(() => window.beaconSnapshot().phase === 'paused');
  assert((await snapshot(mobile)).phase === 'paused', 'Landscape touch Pause activates');
  await mobile.getByRole('button', { name: 'Resume watch ↗' }).tap();
  await mobile.waitForFunction(() => window.beaconSnapshot().phase === 'playing');
  check('Landscape resize preserves square canvas and reachable Pause/Resume controls.');
  await mobileContext.close();
  await page.setViewportSize({ width: 1440, height: 900 });
  assert(report.errors.length === 0 && report.failedRequests.length === 0, 'No browser errors or failed requests');
  return report;
  } catch (error) {
    return { ...report, failure: String(error) };
  }
}
